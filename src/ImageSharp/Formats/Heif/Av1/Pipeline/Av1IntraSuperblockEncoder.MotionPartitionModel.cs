        -0.430317F, -0.0807066F, 0.435906F, 0.522996F, 0.724476F, -0.74371F, -0.05376F,
        -0.340898F, -0.962646F, -0.0278005F, 0.0981149F, -0.0811161F, 0.00237994F, 0.850042F,
        0.0665473F, 0.134413F
    ];

    /// <summary>
    /// Gets the prune rect logits bias 8 model data in row-major order.
    /// </summary>
    private static ReadOnlySpan<float> MotionPruneRectLogitsBias8 =>
    [
        1.63404F, -0.715866F, -1.0132F, -2.08745F
    ];

    /// <summary>
    /// Evaluates a one-hidden-layer partition model without allocating hidden-node storage.
    /// </summary>
    private static void EvaluateMotionPartitionModel(
        ReadOnlySpan<float> features,
        ReadOnlySpan<float> weights0,
        ReadOnlySpan<float> bias0,
        ReadOnlySpan<float> weights1,
        ReadOnlySpan<float> bias1,
        Span<float> scores)
    {
        bias1.CopyTo(scores);
        for (int node = 0; node < bias0.Length; node++)
        {
            float activation = bias0[node];
            for (int feature = 0; feature < features.Length; feature++)
            {
                activation += weights0[(node * features.Length) + feature] * features[feature];
            }

            activation = Math.Max(activation, 0F);
            for (int output = 0; output < scores.Length; output++)
            {
                scores[output] += activation * weights1[(output * bias0.Length) + node];
            }
        }

        for (int output = 0; output < scores.Length; output++)
        {
            scores[output] = (int)((scores[output] * 512F) + 0.5F) * (1F / 512F);
        }
    }

    internal partial struct ModeDecision<TSample, TOperator>
        where TSample : unmanaged
        where TOperator : struct, IBlockEncodingOperator<TSample>
    {
        /// <summary>
        /// Uses whole and quarter-block motion errors to restrict square and rectangular partition searches.
        /// </summary>
        private void PrunePartitionsBySimpleMotion(
            Av1MacroBlockD macroBlock,
            Point blockOrigin,
            Av1BlockSize blockSize,
            int nodeIndex,
            int splitLevel,
            int aggressiveness,
            ref bool allowNone,
            ref bool allowSplit,
            ref bool allowRectangles,
            ref bool pruneHorizontal,
            ref bool pruneVertical)
        {
            Av1EncoderSpeedSettings settings = this.picture.Parent.SpeedSettings;
            int sizeIndex = ((int)Av1BlockSize.Block128x128 - (int)blockSize) / 3;
            int resolution = settings.FourStripPartitionResolutionIndex;
            int splitAggressiveness = aggressiveness == 6 ? 3 : aggressiveness;
            InlineArray32<float> featureStorage = default;
            bool wholeBlock = blockOrigin.X + blockSize.GetWidth() <=
                (this.picture.Parent.Common.ModeInfoColumnCount << Av1Constants.ModeInfoSizeLog2) &&
                blockOrigin.Y + blockSize.GetHeight() <=
                (this.picture.Parent.Common.ModeInfoRowCount << Av1Constants.ModeInfoSizeLog2);

            if (splitLevel != 0 && allowSplit && wholeBlock)
            {
                int modelIndex = splitAggressiveness is 1 or 2 ? 1 : 0;
                ReadOnlySpan<float> means;
                ReadOnlySpan<float> deviations;
                ReadOnlySpan<float> weights0;
                ReadOnlySpan<float> bias0;
                ReadOnlySpan<float> weights1;
                ReadOnlySpan<float> bias1;
                switch (blockSize)
                {
                    case Av1BlockSize.Block128x128:
                        means = MotionSplitMean128;
                        deviations = MotionSplitStd128;
                        weights0 = MotionSplitHiddenlayer0Kernel128;
                        bias0 = MotionSplitHiddenlayer0Bias128;
                        weights1 = MotionSplitLogitsKernel128;
                        bias1 = MotionSplitLogitsBias128;
                        break;
                    case Av1BlockSize.Block64x64:
                        means = MotionSplitMean64;
                        deviations = MotionSplitStd64;
                        weights0 = MotionSplitHiddenlayer0Kernel64;
                        bias0 = MotionSplitHiddenlayer0Bias64;
                        weights1 = MotionSplitLogitsKernel64;
                        bias1 = MotionSplitLogitsBias64;
                        break;
                    case Av1BlockSize.Block32x32:
                        means = MotionSplitMean32;
                        deviations = MotionSplitStd32;
                        weights0 = MotionSplitHiddenlayer0Kernel32;
                        bias0 = MotionSplitHiddenlayer0Bias32;
                        weights1 = MotionSplitLogitsKernel32;
                        bias1 = MotionSplitLogitsBias32;
                        break;
                    case Av1BlockSize.Block16x16:
                        means = MotionSplitMean16;
                        deviations = MotionSplitStd16;
                        weights0 = MotionSplitHiddenlayer0Kernel16;
                        bias0 = MotionSplitHiddenlayer0Bias16;
                        weights1 = MotionSplitLogitsKernel16;
                        bias1 = MotionSplitLogitsBias16;
                        break;
                    case Av1BlockSize.Block8x8:
                        means = MotionSplitMean8;
                        deviations = MotionSplitStd8;
                        weights0 = MotionSplitHiddenlayer0Kernel8;
                        bias0 = MotionSplitHiddenlayer0Bias8;
                        weights1 = MotionSplitLogitsKernel8;
                        bias1 = MotionSplitLogitsBias8;
                        break;
                    default:
                        return;
                }

                Span<float> features = featureStorage[..17];
                InlineArray2<float> output = default;
                this.GetSimpleMotionFeatures(macroBlock, blockOrigin, blockSize, nodeIndex, false, features);
                for (int feature = 0; feature < features.Length; feature++)
                {
                    features[feature] = (features[feature] - means[(modelIndex * 17) + feature]) / deviations[(modelIndex * 17) + feature];
                }

                EvaluateMotionPartitionModel(
                    features,
                    weights0.Slice(modelIndex * weights0.Length / 2, weights0.Length / 2),
                    bias0.Slice(modelIndex * bias0.Length / 2, bias0.Length / 2),
                    weights1.Slice(modelIndex * weights1.Length / 2, weights1.Length / 2),
                    bias1.Slice(modelIndex, 1),
                    output[..1]);

                int thresholdIndex = (splitAggressiveness * 15) + (resolution * 5) + sizeIndex;
                if (output[0] > MotionSplitThresh[thresholdIndex])
                {
                    allowNone = false;
                    allowSplit = true;
                    allowRectangles = false;
                    return;
                }

                if (splitLevel >= 2 && output[0] < MotionNoSplitThresh[thresholdIndex])
                {
                    allowSplit = false;
                }

                if (settings.Speed >= HeifEncodingSpeed.Level3 &&
                    output[0] < (resolution >= 2 ? 3F : 2F) * MotionNoSplitThresh[45 + (resolution * 5) + sizeIndex])
                {
                    allowRectangles = false;
                }
            }

            if (((allowNone && this.IsPartitionCandidateAllowed(blockOrigin, blockSize, Av1PartitionType.None)) || allowSplit) && allowRectangles &&
                ((this.IsPartitionCandidateAllowed(blockOrigin, blockSize, Av1PartitionType.Horizontal) && !pruneHorizontal) ||
                 (this.IsPartitionCandidateAllowed(blockOrigin, blockSize, Av1PartitionType.Vertical) && !pruneVertical)))
            {
                int rectangleAggressiveness = aggressiveness == 6 ? this.blockQIndex <= 90 ? 4 : 3 : aggressiveness;
                float threshold = MotionPruneRectThresh[(rectangleAggressiveness * 15) + (resolution * 5) + sizeIndex];
                if (threshold == 0F)
                {
                    return;
                }

                ReadOnlySpan<float> means;
                ReadOnlySpan<float> deviations;
                ReadOnlySpan<float> weights0;
                ReadOnlySpan<float> bias0;
                ReadOnlySpan<float> weights1;
                ReadOnlySpan<float> bias1;
                switch (blockSize)
                {
                    case Av1BlockSize.Block128x128:
                        means = MotionPruneRectMean128;
                        deviations = MotionPruneRectStd128;
                        weights0 = MotionPruneRectLayer0Kernel128;
                        bias0 = MotionPruneRectLayer0Bias128;
                        weights1 = MotionPruneRectLogitsKernel128;
                        bias1 = MotionPruneRectLogitsBias128;
                        break;
                    case Av1BlockSize.Block64x64:
                        means = MotionPruneRectMean64;
                        deviations = MotionPruneRectStd64;
                        weights0 = MotionPruneRectLayer0Kernel64;
                        bias0 = MotionPruneRectLayer0Bias64;
                        weights1 = MotionPruneRectLogitsKernel64;
                        bias1 = MotionPruneRectLogitsBias64;
                        break;
                    case Av1BlockSize.Block32x32:
                        means = MotionPruneRectMean32;
                        deviations = MotionPruneRectStd32;
                        weights0 = MotionPruneRectLayer0Kernel32;
                        bias0 = MotionPruneRectLayer0Bias32;
                        weights1 = MotionPruneRectLogitsKernel32;
                        bias1 = MotionPruneRectLogitsBias32;
                        break;
                    case Av1BlockSize.Block16x16:
                        means = MotionPruneRectMean16;
                        deviations = MotionPruneRectStd16;
                        weights0 = MotionPruneRectLayer0Kernel16;
                        bias0 = MotionPruneRectLayer0Bias16;
                        weights1 = MotionPruneRectLogitsKernel16;
                        bias1 = MotionPruneRectLogitsBias16;
                        break;
                    case Av1BlockSize.Block8x8:
                        means = MotionPruneRectMean8;
                        deviations = MotionPruneRectStd8;
                        weights0 = MotionPruneRectLayer0Kernel8;
                        bias0 = MotionPruneRectLayer0Bias8;
                        weights1 = MotionPruneRectLogitsKernel8;
                        bias1 = MotionPruneRectLogitsBias8;
                        break;
                    default:
                        return;
                }

                Span<float> features = featureStorage[..25];
                InlineArray16<float> output = default;
                Span<float> scores = output[..bias1.Length];
                this.GetSimpleMotionFeatures(macroBlock, blockOrigin, blockSize, nodeIndex, true, features);
                for (int feature = 0; feature < features.Length; feature++)
                {
                    features[feature] = (features[feature] - means[feature]) / deviations[feature];
                }

                EvaluateMotionPartitionModel(features, weights0, bias0, weights1, bias1, scores);
                float maximum = scores[0];
                for (int index = 1; index < scores.Length; index++)
                {
                    maximum = Math.Max(maximum, scores[index]);
                }

                // Shift all logits equally to prevent overflow, retaining the trained lower exponential bound.
                float sum = 0F;
                for (int index = 0; index < scores.Length; index++)
                {
                    scores[index] = MathF.Exp(Math.Max(scores[index] - maximum, -10F));
                    sum += scores[index];
                }

                pruneHorizontal |= scores[(int)Av1PartitionType.Horizontal] / sum <= threshold;
                pruneVertical |= scores[(int)Av1PartitionType.Vertical] / sum <= threshold;
            }
        }
    }
