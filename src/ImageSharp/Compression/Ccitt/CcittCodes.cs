    /// <summary>
    /// Creates a decode table for one color.
    /// </summary>
    /// <remarks>
    /// A code of length n fills each entry whose first n index bits are the code, 2^(bits - n) entries. The codes of a
    /// color are a prefix code, so each entry belongs to one code at most.
    /// </remarks>
    /// <param name="terminating">The terminating codes of the color.</param>
    /// <param name="makeup">The make-up codes of the color.</param>
    /// <param name="bits">The index bit count.</param>
    /// <returns>The decode table.</returns>
    private static ushort[] CreateRunTable(ReadOnlySpan<ushort> terminating, ReadOnlySpan<uint> makeup, int bits)
    {
        ushort[] table = new ushort[1 << bits];
        for (int run = 0; run < terminating.Length; run++)
        {
            AddCode(table, bits, terminating[run], run);
        }

        for (int i = 0; i < makeup.Length; i++)
        {
            AddCode(table, bits, makeup[i], (i + 1) * 64);
        }

        return table;
    }

    /// <summary>
    /// Adds one code to a decode table.
    /// </summary>
    /// <param name="table">The decode table.</param>
    /// <param name="bits">The index bit count.</param>
    /// <param name="entry">The code entry, (code &lt;&lt; 4) | length.</param>
    /// <param name="run">The run length of the code.</param>
    private static void AddCode(ushort[] table, int bits, uint entry, int run)
    {
        int length = (int)(entry & 0xF);
        int shift = bits - length;
        int first = (int)(entry >> 4) << shift;
        table.AsSpan(first, 1 << shift).Fill((ushort)((run << 4) | length));
    }
