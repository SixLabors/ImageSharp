    internal partial struct ModeDecision<TSample, TOperator>
        where TSample : unmanaged
        where TOperator : struct, IBlockEncodingOperator<TSample>
    {
        /// <summary>
        /// Combines completed child costs, selected geometry, and motion residuals into a stopping decision.
        /// </summary>
        /// <param name="motionSearchPrediction">The prediction buffer of the motion search.</param>
        /// <param name="filterRows">The intermediate rows of the prediction filters.</param>
        /// <param name="motionVectorCosts">The motion vector rates of the frame precision.</param>
        /// <param name="blockOrigin">The luma block origin.</param>
        /// <param name="blockSize">The block size.</param>
        /// <param name="nodeIndex">The simple motion node of the block.</param>
        /// <param name="bestCost">The best partition cost of the block.</param>
        /// <param name="noneCost">The cost of the unsplit block.</param>
        /// <param name="splitCost">The cost of the square split.</param>
        /// <param name="childCosts">The costs of the four split children.</param>
        /// <returns><see langword="true"/> when the remaining partition searches stop.</returns>
        private bool ShouldTerminateAfterSplit(
            Span<TSample> motionSearchPrediction,
            Span<short> filterRows,
            in Av1MotionVectorCosts motionVectorCosts,
            Point blockOrigin,
            Av1BlockSize blockSize,
            int nodeIndex,
            long bestCost,
            long noneCost,
            long splitCost,
            ReadOnlySpan<long> childCosts)
        {
            if (bestCost <= 0 || bestCost == long.MaxValue)
            {
                return false;
            }

            bool largeFrame = this.picture.Parent.SpeedSettings.FourStripPartitionResolutionIndex >= 1;
            ReadOnlySpan<float> weights0;
            ReadOnlySpan<float> bias0;
            ReadOnlySpan<float> weights1;
            float score;
            float threshold;
            switch (blockSize)
            {
                case Av1BlockSize.Block128x128:
                case Av1BlockSize.Block64x64:
                    weights0 = AfterSplit64Weights0;
                    bias0 = AfterSplit64Bias0;
                    weights1 = AfterSplit64Weights1;
                    score = AfterSplit64Bias1[0];
                    threshold = largeFrame ? -2F : -1.2F;
                    break;
                case Av1BlockSize.Block32x32:
                    weights0 = AfterSplit32Weights0;
                    bias0 = AfterSplit32Bias0;
                    weights1 = AfterSplit32Weights1;
                    score = AfterSplit32Bias1[0];
                    threshold = largeFrame ? -2.6F : -2.3F;
                    break;
                case Av1BlockSize.Block16x16:
                    weights0 = AfterSplit16Weights0;
                    bias0 = AfterSplit16Bias0;
                    weights1 = AfterSplit16Weights1;
                    score = AfterSplit16Bias1[0];
                    threshold = largeFrame ? -2F : -2.4F;
                    break;
                case Av1BlockSize.Block8x8:
                    weights0 = AfterSplit8Weights0;
                    bias0 = AfterSplit8Bias0;
                    weights1 = AfterSplit8Weights1;
                    score = AfterSplit8Bias1[0];
                    threshold = largeFrame ? -1F : -1.4F;
                    break;
                default:
                    return false;
            }

            Av1EncoderSpeedSettings settings = this.picture.Parent.SpeedSettings;
            if (settings.AfterSplitTerminationLevel < 2)
            {
                threshold -= 0.3F;
            }

            InlineArray32<float> featureStorage = default;
            Span<float> features = featureStorage;
            int dcStep = Av1QuantizationLookup.GetDcQuant(this.blockQIndex, 0, this.bitDepth) >> (this.bitDepth.GetBitCount() - 8);
            int width = blockSize.GetWidth();
            features[0] = float.LogP1(dcStep / 4F);
            features[1] = float.LogP1((float)bestCost / width / width / 1024F);
            int featureIndex = 2;

            // Preserve a separate validity feature: an unvisited or invalid candidate is not a zero-cost candidate.
            for (int candidate = 0; candidate < 6; candidate++)
            {
                long cost = candidate == 0 ? noneCost : candidate == 1 ? splitCost : childCosts[candidate - 2];
                bool valid = cost > 0 && cost < long.MaxValue;
                features[featureIndex++] = valid ? 1F : 0F;
                features[featureIndex++] = valid ? (float)cost / bestCost : 1F;
                if (candidate >= 2)
                {
                    int minimumWidth = Av1Constants.MaxSuperBlockSizeLog2;
                    int minimumHeight = Av1Constants.MaxSuperBlockSizeLog2;
                    this.GetMinimumSimpleMotionBlockSize(
                        Av1PartitionType.Split.GetBlockSubSize(blockSize),
                        (nodeIndex * 4) + candidate - 1,
                        ref minimumWidth,
                        ref minimumHeight);

                    features[featureIndex++] = minimumWidth;
                    features[featureIndex++] = minimumHeight;
                }
            }

            this.CollectSimpleMotionFeatures(motionSearchPrediction, filterRows, in motionVectorCosts, blockOrigin, blockSize, nodeIndex, true);
            Span<Av1SimpleMotionData> nodes = this.blockWorkspace.SimpleMotionData;
            features[featureIndex++] = float.LogP1(nodes[nodeIndex].Variance);
            for (int child = 0; child < 4; child++)
            {
                features[featureIndex++] = float.LogP1(nodes[(nodeIndex * 4) + child + 1].Variance);
            }

            for (int rectangle = 0; rectangle < 4; rectangle++)
            {
                features[featureIndex++] = float.LogP1(nodes[nodeIndex].RectangleVariances[rectangle]);
            }

            // Consume each activated hidden node immediately; the single output needs no intermediate array.
            for (int node = 0; node < bias0.Length; node++)
            {
                float activation = bias0[node];
                for (int feature = 0; feature < 31; feature++)
                {
                    activation += weights0[(node * 31) + feature] * features[feature];
                }

                score += Math.Max(activation, 0F) * weights1[node];
            }

            // The model's output precision is nine fractional bits, including truncation for negative scores.
            score = (int)((score * 512F) + 0.5F) * (1F / 512F);
            return score < threshold;
        }

        /// <summary>
        /// Finds the smallest selected width and height beneath a square, measured in log2 mode-information units.
        /// </summary>
        private void GetMinimumSimpleMotionBlockSize(Av1BlockSize blockSize, int nodeIndex, ref int minimumWidth, ref int minimumHeight)
        {
            if (blockSize == Av1BlockSize.Block4x4)
            {
                minimumWidth = 0;
                minimumHeight = 0;
                return;
            }

            Av1PartitionType partition = this.blockWorkspace.SimpleMotionData[nodeIndex].Partition;
            if (partition == Av1PartitionType.Split)
            {
                Av1BlockSize childSize = partition.GetBlockSubSize(blockSize);
                for (int child = 0; child < 4; child++)
                {
                    this.GetMinimumSimpleMotionBlockSize(childSize, (nodeIndex * 4) + child + 1, ref minimumWidth, ref minimumHeight);
                }
            }
            else if (partition != Av1PartitionType.Invalid)
            {
                // An asymmetric partition contains a square quarter as well as its rectangular half.
                if (partition is Av1PartitionType.HorizontalA or Av1PartitionType.HorizontalB or
                    Av1PartitionType.VerticalA or Av1PartitionType.VerticalB)
                {
                    partition = Av1PartitionType.Split;
                }

                Av1BlockSize childSize = partition.GetBlockSubSize(blockSize);
                minimumWidth = Math.Min(minimumWidth, BitOperations.Log2((uint)childSize.GetWidth()) - Av1Constants.ModeInfoSizeLog2);
                minimumHeight = Math.Min(minimumHeight, BitOperations.Log2((uint)childSize.GetHeight()) - Av1Constants.ModeInfoSizeLog2);
            }
        }
    }
