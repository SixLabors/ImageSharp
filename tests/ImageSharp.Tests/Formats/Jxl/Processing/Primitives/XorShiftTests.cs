    [Fact]
    public void TestFloat()
    {
#if ALLOW_JPEGXL_SLOW_TESTS
        const int seedMax = 4096;
#else
        const int seedMax = 256;
#endif

        Parallel.For(0, seedMax, seed =>
        {
            const int VecCap = 16;

            JxlXorShift rng = new((ulong)seed);

            Span<ulong> batch64 = stackalloc ulong[JxlXorShift.Generators];
            Span<uint> batch32 = stackalloc uint[2 * JxlXorShift.Generators];

            Span<float> lanes = stackalloc float[Vector<float>.Count];

            int count = 0;
            const int reps = 32000;
            double sum = 0.0;
            while (count < reps)
            {
                rng.Fill(batch64);

                MemoryMarshal.Cast<ulong, uint>(batch64).CopyTo(batch32);

                for (int i = 0; i < VecCap; i += Vector<float>.Count)
                {
                    Vector<uint> bits = new(batch32.Slice(i, Vector<uint>.Count));

                    // (bits >> 9) | 0x3F800000
                    Vector<uint> shifted = bits >> 9;
                    Vector<uint> mantissa = shifted | new Vector<uint>(0x3F800000);

                    Vector<float> rand12 = Vector.AsVectorSingle(mantissa);

                    rand12.CopyTo(lanes);

                    for (int j = 0; j < Vector<float>.Count; j++)
                    {
                        float lane = lanes[j];
                        sum += lane;
                        count++;

                        Assert.True(lane < 2.0f);
                        Assert.True(lane >= 1.0f);
                    }
                }
            }
        });
    }

    [Fact]
    public void TestNotZero()
    {
#if ALLOW_JPEGXL_SLOW_TESTS
        const int seedMax = 2000;
#else
        const int seedMax = 500;
#endif

        Parallel.For(0, seedMax, task =>
        {
            Span<ulong> lanes = stackalloc ulong[JxlXorShift.Generators];
            JxlXorShift rng = new((ulong)task);
            int numZero = 0;

            for (int vectors = 0; vectors < 10000; vectors++)
            {
                rng.Fill(lanes);
                for (int i = 0; i < lanes.Length; i++)
                {
                    if (lanes[i] == 0)
                    {
                        numZero++;
                    }
                }
            }

            Assert.True(numZero < 1, "There should not be any 0 values produced by the RNG");
        });
    }
