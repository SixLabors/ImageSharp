            if (retainedScores[first] < retainedScores[second])
            {
                (retainedScores[first], retainedScores[second]) = (retainedScores[second], retainedScores[first]);
                (order[first], order[second]) = (order[second], order[first]);
            }
        }

        if (pruningLevel >= 4)
        {
            float accumulatedScore = 0;
            float percentage = 0;
            float inverseSum = 100F / retainedSum;
            int count = 0;
            while (count < retainedCount && (percentage <= 30F || count < 2))
            {
                accumulatedScore += retainedScores[count++];
                percentage = accumulatedScore * inverseSum;
            }

            for (int index = count; index < retainedCount; index++)
            {
                retainedMask &= (ushort)~(1 << (int)order[index]);
            }
        }

        return retainedMask;
    }

    /// <summary>
    /// Computes the normalized horizontal and vertical energy projections of a residual block. The residual is
    /// downscaled to at most an 8x8 grid of squared-sample sums, which stay integers, and the projections sum the
    /// grid as floats in the reference order: each horizontal feature adds the rows top to bottom and each
    /// vertical feature adds the columns left to right. Reference: get_energy_distribution_finer().
    /// </summary>
    /// <param name="residual">The residual samples.</param>
    /// <param name="stride">The residual row stride.</param>
    /// <param name="width">The block width: four, eight or sixteen.</param>
    /// <param name="height">The block height: four, eight or sixteen.</param>
    /// <param name="horizontalFeatures">Receives the grid width minus one horizontal features.</param>
    /// <param name="verticalFeatures">Receives the grid height minus one vertical features.</param>
    internal static void GetEnergyDistribution(
        ReadOnlySpan<short> residual,
        int stride,
        int width,
        int height,
        Span<float> horizontalFeatures,
        Span<float> verticalFeatures)
    {
        int heightShift = height <= 8 ? 0 : 1;
        int energyWidth = width <= 8 ? width : width >> 1;
        int energyHeight = height >> heightShift;

        // Each grid row is one eight-lane vector; lanes past the grid width stay zero. A cell holds at most four
        // squared twelve-bit samples, so the 32-bit lanes cannot overflow.
        InlineArray8<Vector256<int>> grid = default;
        ref short residualBase = ref MemoryMarshal.GetReference(residual);
        for (int y = 0; y < height; y++)
        {
            ref short row = ref Unsafe.Add(ref residualBase, y * stride);
            Vector256<int> cells;
            if (width == 16)
            {
                // Two horizontally adjacent squares share a cell, which is one multiply-add of the row with itself.
                Vector256<short> samples = Vector256.LoadUnsafe(ref row);
                cells = Vector256_.MultiplyAddAdjacent(samples, samples);
            }
            else if (width == 8)
            {
                Vector256<int> samples = Vector256_.Widen(Vector128.LoadUnsafe(ref row));
                cells = samples * samples;
            }
            else
            {
                Vector128<int> samples = Vector128.WidenLower(Vector128.CreateScalarUnsafe(Unsafe.ReadUnaligned<long>(ref Unsafe.As<short, byte>(ref row))).AsInt16());
                cells = Vector256.Create(samples * samples, Vector128<int>.Zero);
            }

            grid[y >> heightShift] += cells;
        }

        Vector256<ulong> total = Vector256<ulong>.Zero;
        for (int y = 0; y < energyHeight; y++)
        {
            (Vector256<ulong> lower, Vector256<ulong> upper) = Vector256.Widen(grid[y].AsUInt32());
            total += lower + upper;
        }

        ulong totalEnergy = Vector256.Sum(total);
        if (totalEnergy == 0)
        {
            horizontalFeatures[..(energyWidth - 1)].Fill(1F / energyWidth);
            verticalFeatures[..(energyHeight - 1)].Fill(1F / energyHeight);
            return;
        }

        // Each lane of the horizontal sum is one column, so adding the rows in order keeps the reference's
        // floating-point order. The transposed grid gives the vertical sums the same property.
        InlineArray8<Vector256<float>> cellValues = default;
        Vector256<float> horizontal = Vector256<float>.Zero;
        for (int y = 0; y < energyHeight; y++)
        {
            cellValues[y] = Vector256.ConvertToSingle(grid[y]);
            horizontal += cellValues[y];
        }

        Av1Transform2dOperations.Transpose(
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[0]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[1]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[2]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[3]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[4]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[5]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[6]),
            ref Unsafe.As<Vector256<float>, Vector256<int>>(ref cellValues[7]));

        Vector256<float> vertical = Vector256<float>.Zero;
        for (int x = 0; x < energyWidth; x++)
        {
            vertical += cellValues[x];
        }

        Vector256<float> reciprocal = Vector256.Create(1F / totalEnergy);
        InlineArray8<float> values = default;
        (horizontal * reciprocal).StoreUnsafe(ref values[0]);
        ((ReadOnlySpan<float>)values)[..(energyWidth - 1)].CopyTo(horizontalFeatures);
        (vertical * reciprocal).StoreUnsafe(ref values[0]);
        ((ReadOnlySpan<float>)values)[..(energyHeight - 1)].CopyTo(verticalFeatures);
    }

    /// <summary>
    /// Evaluates the four one-dimensional transform scores for one axis.
    /// </summary>
    private static void EvaluateTransformAxis(
        Av1TransformSize transformSize,
        bool vertical,
        ReadOnlySpan<float> features,
        Span<float> scores)
    {
        ReadOnlySpan<float> weights;
        ReadOnlySpan<float> bias;
        ReadOnlySpan<float> outputWeights;
        ReadOnlySpan<float> outputBias;
        switch (transformSize)
        {
            case Av1TransformSize.Size4x4:
                weights = vertical ? TransformType4x4VerticalWeights0 : TransformType4x4HorizontalWeights0;
                bias = vertical ? TransformType4x4VerticalBias0 : TransformType4x4HorizontalBias0;
                outputWeights = vertical ? TransformType4x4VerticalWeights1 : TransformType4x4HorizontalWeights1;
                outputBias = vertical ? TransformType4x4VerticalBias1 : TransformType4x4HorizontalBias1;
                break;
            case Av1TransformSize.Size8x8:
                weights = vertical ? TransformType8x8VerticalWeights0 : TransformType8x8HorizontalWeights0;
                bias = vertical ? TransformType8x8VerticalBias0 : TransformType8x8HorizontalBias0;
                outputWeights = vertical ? TransformType8x8VerticalWeights1 : TransformType8x8HorizontalWeights1;
                outputBias = vertical ? TransformType8x8VerticalBias1 : TransformType8x8HorizontalBias1;
                break;
            case Av1TransformSize.Size4x8:
                weights = vertical ? TransformType4x8VerticalWeights0 : TransformType4x8HorizontalWeights0;
                bias = vertical ? TransformType4x8VerticalBias0 : TransformType4x8HorizontalBias0;
                outputWeights = vertical ? TransformType4x8VerticalWeights1 : TransformType4x8HorizontalWeights1;
                outputBias = vertical ? TransformType4x8VerticalBias1 : TransformType4x8HorizontalBias1;
                break;
            case Av1TransformSize.Size8x4:
                weights = vertical ? TransformType8x4VerticalWeights0 : TransformType8x4HorizontalWeights0;
                bias = vertical ? TransformType8x4VerticalBias0 : TransformType8x4HorizontalBias0;
                outputWeights = vertical ? TransformType8x4VerticalWeights1 : TransformType8x4HorizontalWeights1;
                outputBias = vertical ? TransformType8x4VerticalBias1 : TransformType8x4HorizontalBias1;
                break;
            case Av1TransformSize.Size8x16:
                weights = vertical ? TransformType8x16VerticalWeights0 : TransformType8x16HorizontalWeights0;
                bias = vertical ? TransformType8x16VerticalBias0 : TransformType8x16HorizontalBias0;
                outputWeights = vertical ? TransformType8x16VerticalWeights1 : TransformType8x16HorizontalWeights1;
                outputBias = vertical ? TransformType8x16VerticalBias1 : TransformType8x16HorizontalBias1;
                break;
            case Av1TransformSize.Size16x8:
                weights = vertical ? TransformType16x8VerticalWeights0 : TransformType16x8HorizontalWeights0;
                bias = vertical ? TransformType16x8VerticalBias0 : TransformType16x8HorizontalBias0;
                outputWeights = vertical ? TransformType16x8VerticalWeights1 : TransformType16x8HorizontalWeights1;
                outputBias = vertical ? TransformType16x8VerticalBias1 : TransformType16x8HorizontalBias1;
                break;
            case Av1TransformSize.Size4x16:
                weights = vertical ? TransformType4x16VerticalWeights0 : TransformType4x16HorizontalWeights0;
                bias = vertical ? TransformType4x16VerticalBias0 : TransformType4x16HorizontalBias0;
                outputWeights = vertical ? TransformType4x16VerticalWeights1 : TransformType4x16HorizontalWeights1;
                outputBias = vertical ? TransformType4x16VerticalBias1 : TransformType4x16HorizontalBias1;
                break;
            case Av1TransformSize.Size16x4:
                weights = vertical ? TransformType16x4VerticalWeights0 : TransformType16x4HorizontalWeights0;
                bias = vertical ? TransformType16x4VerticalBias0 : TransformType16x4HorizontalBias0;
                outputWeights = vertical ? TransformType16x4VerticalWeights1 : TransformType16x4HorizontalWeights1;
                outputBias = vertical ? TransformType16x4VerticalBias1 : TransformType16x4HorizontalBias1;
                break;
            default:
                weights = TransformType16x16Weights0;
                bias = TransformType16x16Bias0;
                outputWeights = TransformType16x16Weights1;
                outputBias = TransformType16x16Bias1;
                break;
        }

        InlineArray16<float> hiddenStorage = default;
        Span<float> hidden = hiddenStorage;
        for (int node = 0; node < bias.Length; node++)
        {
            float value = bias[node];
            ReadOnlySpan<float> nodeWeights = weights.Slice(node * features.Length, features.Length);
            for (int feature = 0; feature < features.Length; feature++)
            {
                value += nodeWeights[feature] * features[feature];
            }

            hidden[node] = value > 0 ? value : 0;
        }

        // Reuse the rectified hidden outputs for all four transform families. Each output is
        // rounded independently before horizontal and vertical scores are combined.
        for (int output = 0; output < 4; output++)
        {
            float value = outputBias[output];
            ReadOnlySpan<float> nodeWeights = outputWeights.Slice(output * bias.Length, bias.Length);
            for (int node = 0; node < bias.Length; node++)
            {
                value += nodeWeights[node] * hidden[node];
            }

            scores[output] = (int)((value * 512F) + 0.5F) * (1F / 512F);
        }
    }
