        {
            ReadOnlySpan<int> cospi = Av1SinusConstants.CosinusPi(cosBit);
            int stage = 0;

            // Stage 1 permutes frequency-ordered coefficients into the recursive DCT factorization order.
            stage++;
            output[0] = input[0];
            output[1] = input[32];
            output[2] = input[16];
            output[3] = input[48];
            output[4] = input[8];
