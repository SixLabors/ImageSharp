    internal partial struct ModeDecision<TSample, TOperator>
        where TSample : unmanaged
        where TOperator : struct, IBlockEncodingOperator<TSample>
    {
        /// <summary>
        /// Resolves horizontal and vertical four-strip candidates using the configured texture classifier.
        /// </summary>
        private int ClassifyFourStripPartitions(
            Point blockOrigin,
            Av1BlockSize blockSize,
            Av1PartitionType winner,
            long bestCost,
            int sourceVariance,
            ReadOnlySpan<long> horizontalCosts,
            ReadOnlySpan<long> verticalCosts,
            ReadOnlySpan<long> splitNoneCosts,
            int currentMask)
        {
            if (bestCost >= 1000000000)
            {
                return currentMask;
            }

            Av1EncoderSpeedSettings settings = this.picture.Parent.SpeedSettings;
            bool normalized = settings.FourStripPartitionModelLevel < 3;
            Span<float> features = stackalloc float[18];
            features[0] = (int)winner;
            features[1] = 32 - BitOperations.LeadingZeroCount((uint)sourceVariance);
            for (int index = 0; index < 8; index++)
            {
                long cost = index < 2 ? horizontalCosts[index] :
                    index < 4 ? verticalCosts[index - 2] : splitNoneCosts[index - 4];
                features[index + 2] = cost > 0 && cost < 1000000000 && cost < bestCost
                    ? (float)cost / bestCost
                    : 1F;
            }

            // Add one to both variances before division to retain flat strips. Bound texture ratios
            // before normalization so a nearly flat parent cannot produce unbounded model inputs.
            Av1BlockSize horizontalSize = Av1PartitionType.Horizontal4.GetBlockSubSize(blockSize);
            Av1BlockSize verticalSize = Av1PartitionType.Vertical4.GetBlockSubSize(blockSize);
            float denominator = sourceVariance + 1;
            for (int strip = 0; strip < 4; strip++)
            {
                Point horizontalOrigin = new(blockOrigin.X, blockOrigin.Y + (strip * horizontalSize.GetHeight()));
                Point verticalOrigin = new(blockOrigin.X + (strip * verticalSize.GetWidth()), blockOrigin.Y);
                features[10 + strip] = Math.Clamp((this.GetSourceVariance(horizontalOrigin, horizontalSize) + 1) / denominator, 0.1F, 10F);
                features[14 + strip] = Math.Clamp((this.GetSourceVariance(verticalOrigin, verticalSize) + 1) / denominator, 0.1F, 10F);
            }

            ReadOnlySpan<float> weights;
            ReadOnlySpan<float> biases;
            ReadOnlySpan<float> outputWeights;
            ReadOnlySpan<float> outputBiases;
            ReadOnlySpan<float> means;
            ReadOnlySpan<float> deviations;
            switch (blockSize)
            {
                case Av1BlockSize.Block16x16:
                    weights = normalized ? FourStripNormalized16Weights0 : FourStrip16Weights0;
                    biases = normalized ? FourStripNormalized16Bias0 : FourStrip16Bias0;
                    outputWeights = normalized ? FourStripNormalized16Weights1 : FourStrip16Weights1;
                    outputBiases = normalized ? FourStripNormalized16Bias1 : FourStrip16Bias1;
                    means = FourStrip16Means;
                    deviations = FourStrip16Deviations;
                    break;
                case Av1BlockSize.Block32x32:
                    weights = normalized ? FourStripNormalized32Weights0 : FourStrip32Weights0;
                    biases = normalized ? FourStripNormalized32Bias0 : FourStrip32Bias0;
                    outputWeights = normalized ? FourStripNormalized32Weights1 : FourStrip32Weights1;
                    outputBiases = normalized ? FourStripNormalized32Bias1 : FourStrip32Bias1;
                    means = FourStrip32Means;
                    deviations = FourStrip32Deviations;
                    break;
                default:
                    weights = normalized ? FourStripNormalized64Weights0 : FourStrip64Weights0;
                    biases = normalized ? FourStripNormalized64Bias0 : FourStrip64Bias0;
                    outputWeights = normalized ? FourStripNormalized64Weights1 : FourStrip64Weights1;
                    outputBiases = normalized ? FourStripNormalized64Bias1 : FourStrip64Bias1;
                    means = FourStrip64Means;
                    deviations = FourStrip64Deviations;
                    break;
            }

            if (normalized)
            {
                for (int feature = 0; feature < features.Length; feature++)
                {
                    features[feature] = (features[feature] - means[feature]) / deviations[feature];
                }
            }

            InlineArray4<float> scores = default;
            int outputCount = outputBiases.Length;
            int hiddenCount = biases.Length;
            for (int output = 0; output < outputCount; output++)
            {
                scores[output] = outputBiases[output];
            }

            // The normalized models have three outputs; the unnormalized models encode four masks.
            // Both consume each hidden activation directly in ascending order without an activation buffer.
            for (int node = 0; node < hiddenCount; node++)
            {
                float value = biases[node];
                int offset = node * features.Length;
                for (int feature = 0; feature < features.Length; feature++)
                {
                    value += weights[offset + feature] * features[feature];
                }

                value = Math.Max(value, 0);
                for (int output = 0; output < outputCount; output++)
                {
                    scores[output] += outputWeights[(output * hiddenCount) + node] * value;
                }
            }

            for (int output = 0; output < outputCount; output++)
            {
                scores[output] = (int)((scores[output] * 512F) + 0.5) * (1F / 512F);
            }

            if (!normalized)
            {
                InlineArray4<int> integerScores = default;
                int maximum = -1000;
                for (int output = 0; output < 4; output++)
                {
                    integerScores[output] = (int)(100 * scores[output]);
                    maximum = Math.Max(maximum, integerScores[output]);
                }

                int threshold = maximum - (blockSize == Av1BlockSize.Block64x64 ? 200 : 500);
                int mask = 0;
                for (int output = 0; output < 4; output++)
                {
                    if (integerScores[output] >= threshold)
                    {
                        mask |= output;
                    }
                }

                return mask;
            }

            float largest = Math.Max(scores[0], Math.Max(scores[1], scores[2]));
            float sum = 0;
            for (int output = 0; output < 3; output++)
            {
                scores[output] = MathF.Exp(Math.Max(scores[output] - largest, -10F));
                sum += scores[output];
            }

            int sizeIndex = ((int)Av1BlockSize.Block128x128 - (int)blockSize) / 3;
            int thresholdIndex = (settings.FourStripPartitionModelLevel * 15) + (settings.FourStripPartitionResolutionIndex * 5) + sizeIndex;
            float searchThreshold = FourStripSearchThresholds[thresholdIndex];
            float rejectThreshold = FourStripRejectThresholds[thresholdIndex];
            for (int direction = 0; direction < 2; direction++)
            {
                float probability = scores[direction + 1] / sum;
                if (probability >= searchThreshold)
                {
                    currentMask |= 1 << direction;
                }

                if (probability < rejectThreshold)
                {
                    currentMask &= ~(1 << direction);
                }
            }

            return currentMask;
        }
    }
