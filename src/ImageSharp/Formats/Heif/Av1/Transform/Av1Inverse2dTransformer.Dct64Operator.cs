            output[60] = input[15];
            output[61] = input[47];
            output[62] = input[31];
            output[63] = input[63];

            // Stage 2 rotates the highest odd-frequency coefficient pairs by their pi/128 angles.
            stage++;
            step[0] = output[0];
            step[1] = output[1];
            step[2] = output[2];
            step[3] = output[3];
            step[4] = output[4];
            step[5] = output[5];
