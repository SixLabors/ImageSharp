            long noneCost,
            int sourceVariance,
            ReadOnlySpan<long> splitNoneCosts,
            out bool pruneHorizontal,
            out bool pruneVertical)
        {
            pruneHorizontal = false;
            pruneVertical = false;
            if (blockSize < Av1BlockSize.Block8x8 || bestCost >= 1000000000)
            {
                return;
            }

            // The cost ratios divide by a best cost of at least one, so a zero cost cannot make them infinite.
            bestCost = Math.Max(bestCost, 1);
            Span<float> features = stackalloc float[9];
            features[..5].Fill(1);
            if (noneCost > 0 && noneCost < 1000000000)
            {
                features[0] = (float)noneCost / bestCost;
            }

            for (int child = 0; child < 4; child++)
            {
                long cost = splitNoneCosts[child];
                if (cost > 0 && cost < 1000000000)
                {
                    features[child + 1] = (float)cost / bestCost;
                }
            }

            // Normalize each quarter's centered variance against the complete block. Padded samples
            // remain part of the coded geometry; cropping to the visible image would change the features.
            int wholeVariance = Math.Max(sourceVariance, 1);
            Av1BlockSize childSize = Av1PartitionType.Split.GetBlockSubSize(blockSize);
            int halfWidth = blockSize.GetWidth() >> 1;
            for (int child = 0; child < 4; child++)
            {
                Point origin = new(blockOrigin.X + ((child & 1) * halfWidth), blockOrigin.Y + ((child >> 1) * halfWidth));
                features[child + 5] = (float)this.GetSourceVariance(sourceLuma, sourceBlue, sourceRed, midpoint, origin, childSize) / wholeVariance;
            }

            ReadOnlySpan<float> weights;
            ReadOnlySpan<float> biases;
            ReadOnlySpan<float> outputWeights;
            ReadOnlySpan<float> outputBiases;
            float threshold;
            switch (blockSize)
            {
                case Av1BlockSize.Block8x8:
                    weights = Rectangle8Weights0;
                    biases = Rectangle8Bias0;
                    outputWeights = Rectangle8Weights1;
                    outputBiases = Rectangle8Bias1;
                    threshold = 0.01F;
                    break;
                case Av1BlockSize.Block16x16:
                    weights = Rectangle16Weights0;
                    biases = Rectangle16Bias0;
                    outputWeights = Rectangle16Weights1;
                    outputBiases = Rectangle16Bias1;
                    threshold = 0.01F;
                    break;
                case Av1BlockSize.Block32x32:
                    weights = Rectangle32Weights0;
                    biases = Rectangle32Bias0;
                    outputWeights = Rectangle32Weights1;
                    outputBiases = Rectangle32Bias1;
                    threshold = 0.004F;
                    break;
                case Av1BlockSize.Block64x64:
                    weights = Rectangle64Weights0;
                    biases = Rectangle64Bias0;
                    outputWeights = Rectangle64Weights1;
                    outputBiases = Rectangle64Bias1;
                    threshold = 0.002F;
                    break;
                default:
                    weights = Rectangle128Weights0;
                    biases = Rectangle128Bias0;
                    outputWeights = Rectangle128Weights1;
                    outputBiases = Rectangle128Bias1;
                    threshold = 0.002F;
                    break;
            }

            InlineArray3<float> scoreStorage = default;
            Span<float> scores = scoreStorage;
            Av1NeuralNetwork.Predict(features, weights, biases, outputWeights, outputBiases, scores);

            // Subtract the largest score before exponentiation, then bound the negative tail.
            // The three classes represent neither direction, horizontal, and vertical respectively.
            float maximum = Math.Max(scores[0], Math.Max(scores[1], scores[2]));
            float sum = 0;
            for (int output = 0; output < 3; output++)
            {
                scores[output] = MathF.Exp(Math.Max(scores[output] - maximum, -10F));
                sum += scores[output];
            }

            pruneHorizontal = scores[1] / sum <= threshold;
            pruneVertical = scores[2] / sum <= threshold;
        }
    }
