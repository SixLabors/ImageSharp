    /// <summary>
    /// Builds the parent and subregion residual features shared by transform subdivision models.
    /// </summary>
    private static int GetTransformSplitFeatures(ReadOnlySpan<short> residual, Av1TransformSize transformSize, Span<float> features)
    {
        int width = transformSize.GetWidth();
        int height = transformSize.GetHeight();
        int subWidth = width >= height ? width >> 1 : width;
        int subHeight = height >= width ? height >> 1 : height;
        int subArea = subWidth * subHeight;
        int featureCount = 2;
        int sum = 0;
        long squaredSum = 0;
        double squaredMeanSum = 0;
        float deviationSum = 0;
        int subCount = 0;

        // A square transform contributes four subregions and a rectangle contributes two. Each pair stores a mean followed by a standard
        // deviation, in raster order.
        for (int y = 0; y < height; y += subHeight)
        {
            for (int x = 0; x < width; x += subWidth)
            {
                long subSquaredSum = Av1ResidualBuilder.SumAndSumSquares(residual[((y * width) + x)..], width, subWidth, subHeight, out long blockSum);
                int subSum = (int)blockSum;
                sum += subSum;
                squaredSum += subSquaredSum;
                float mean = (float)subSum / subArea;
                float variance = (float)((double)subSquaredSum / subArea) - (mean * mean);
                float deviation = variance > 0 ? MathF.Sqrt(variance) : 0;
                features[featureCount++] = mean;
                features[featureCount++] = deviation;
                squaredMeanSum += mean * mean;
                deviationSum += deviation;
                subCount++;
            }
        }

        int area = width * height;
        float parentMean = (float)sum / area;
        float parentVariance = (float)((double)squaredSum / area) - (parentMean * parentMean);
        features[0] = parentMean;
        features[1] = parentVariance > 0 ? MathF.Sqrt(parentVariance) : 0;
        float meanVariance = (float)(squaredMeanSum / subCount) - (parentMean * parentMean);
        features[featureCount++] = meanVariance > 0 ? MathF.Sqrt(meanVariance) : 0;
        features[featureCount++] = deviationSum / subCount;

        return featureCount;
    }

    /// <summary>
    /// Classifies the eight-bit 8x8 intra residual as unsplit, split, or undecided.
    /// </summary>
    /// <param name="residual">The residual samples in contiguous transform rows.</param>
    /// <param name="sourceVariance">The source variance of the block.</param>
    /// <param name="dcQuantizer">The DC quantizer step, scaled to eight bits.</param>
    /// <returns>Minus one to omit the smaller size, one to omit the largest size, or zero to evaluate both.</returns>
    private static int PredictIntraTransformDepth(ReadOnlySpan<short> residual, int sourceVariance, int dcQuantizer)
    {
        InlineArray16<float> featureStorage = default;
        Span<float> features = featureStorage;
        int featureCount = GetTransformSplitFeatures(residual, Av1TransformSize.Size8x8, features);
        features[featureCount++] = float.LogP1(sourceVariance);
        features[featureCount++] = float.LogP1((float)(dcQuantizer * dcQuantizer) / 256F);
        for (int index = 0; index < featureCount; index++)
        {
            features[index] = (features[index] - IntraTransformFeatureMeans[index]) / IntraTransformFeatureDeviations[index];
        }

        float score = 0F;
        Av1NeuralNetwork.Predict(
            features[..featureCount],
            IntraTransformWeights,
            IntraTransformBias,
            IntraTransformOutputWeights,
            IntraTransformOutputBias,
            new Span<float>(ref score));

        return score <= -0.405465F ? -1 : score > 0.405465F ? 1 : 0;
    }
